const decl = /^\s*(?:private\[?\w*\]?\s+|final\s+|abstract\s+|sealed\s+|implicit\s+)*(object|class|case class|trait)\s+([A-Za-z0-9_]+)/;
const all = [];
for (const f of files) {
  const L = fs.readFileSync(f, "utf8").split(/\r?\n/);
  for (let i = 0; i < L.length; i++) {
    const m = L[i].match(decl);
    if (!m) continue;
    // read the header: skip anything inside (...) or [...], stop at "{" or "=" at depth 0
    let depth = 0, hdr = "", done = false;
    for (let k = 0; k < 80 && i + k < L.length && !done; k++) {
      const line = L[i + k];
      for (let c = 0; c < line.length; c++) {
        const ch = line[c];
        if (ch === "(" || ch === "[") depth++;
        else if (ch === ")" || ch === "]") depth--;
        if (depth === 0 && (ch === "{" || (ch === "=" && line[c + 1] !== ">" && line[c - 1] !== "="))) { done = true; break; }
        if (depth === 0) hdr += ch;
      }
      hdr += " ";
    }
    const e = hdr.indexOf(" extends ");
    if (e < 0) continue;
    const tail = hdr.slice(e + 9);
    const parents = tail.split(" with ").map(s => s.trim()).map(s => s.split(/\s/)[0]).map(s => s.split(".").pop()).filter(Boolean);
    all.push({ name: m[2], kind: m[1], file: f, line: i + 1, parents });
  }
}
